"""Build the generated site files that the pages read under file://.

  assets/js/sources-data.js  WE.BIB (sources/bibliography.csv) and WE.SERIES
                             (metadata of every data/clean/*/*.json, no values)
  assets/js/search-index.js  WE.SEARCH: one document per h2 section of every
                             finished chapter, plus one per glossary term

Run after build_data.py and whenever a chapter changes:
    python3 scripts/build_site_meta.py
"""
import csv, glob, html, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
J = lambda *p: os.path.join(ROOT, *p)


def strip(s):
    s = re.sub(r"<script.*?</script>", " ", s, flags=re.S)
    s = re.sub(r"<sup class=\"fn\">.*?</sup>", "", s, flags=re.S)
    s = re.sub(r"<[^>]+>", " ", s)
    return re.sub(r"\s+", " ", html.unescape(s)).strip()


def sources_data():
    with open(J("sources", "bibliography.csv"), newline="", encoding="utf-8") as f:
        bib = list(csv.DictReader(f))
    series = []
    for p in sorted(glob.glob(J("data", "clean", "*", "*.json"))):
        if "/derived/" in p:
            continue
        with open(p, encoding="utf-8") as f:
            d = json.load(f)
        if not isinstance(d, dict) or "id" not in d:
            continue
        data = d.get("data") or {}
        periods = [pt[0] for v in data.values() if isinstance(v, list) for pt in v if pt]
        series.append({k: d.get(k) for k in ("id", "source", "code", "label", "unit", "freq", "vintage", "url", "retrieved", "notes")}
                      | {"areas": len(data), "first": str(min(periods)) if periods else "", "last": str(max(periods)) if periods else ""})
    out = "/* Generated by scripts/build_site_meta.py. Do not edit. */\nwindow.WE = window.WE || {};\n"
    out += "WE.BIB = " + json.dumps(bib, ensure_ascii=False) + ";\n"
    out += "WE.SERIES = " + json.dumps(series, ensure_ascii=False) + ";\n"
    with open(J("assets", "js", "sources-data.js"), "w", encoding="utf-8") as f:
        f.write(out)
    print(f"sources-data.js: {len(bib)} sources, {len(series)} series")


def glossary_terms():
    txt = open(J("assets", "js", "glossary-data.js"), encoding="utf-8").read()
    return re.findall(r'"([a-z0-9-]+)":\s*\{\s*term:\s*"([^"]+)",\s*def:\s*"((?:[^"\\]|\\.)*)"', txt)


def search_index():
    docs, n = [], 0
    for p in sorted(glob.glob(J("chapters", "*.html"))):
        src = open(p, encoding="utf-8").read()
        rel = "chapters/" + os.path.basename(p)
        title = strip(re.search(r"<h1>(.*?)</h1>", src, re.S).group(1))
        body = src.split("<article", 1)[1].split("</article>", 1)[0]
        body = body.split('<h2 id="notes">', 1)[0]
        parts = re.split(r'<h2 id="([^"]+)">(.*?)</h2>', body, flags=re.S)
        intro = strip(parts[0])
        docs.append({"id": n, "title": title, "section": "Introduction", "href": rel, "text": intro}); n += 1
        for i in range(1, len(parts), 3):
            docs.append({"id": n, "title": title + ": " + strip(parts[i + 1]), "section": title,
                         "href": rel + "#" + parts[i], "text": strip(parts[i + 2])}); n += 1
    # front and back matter: one entry per page section
    for page in ["about.html", "explorer.html", "map.html", "wdr-shelf.html"]:
        src = open(J(page), encoding="utf-8").read()
        title = strip(re.search(r"<h1>(.*?)</h1>", src, re.S).group(1))
        body = src.split("<article", 1)[1].split("</article>", 1)[0].split('<section class="footnotes"', 1)[0]
        body = re.sub(r'<div class="wdr-grid.*?</div>\n(?=\s*$|\s*<)', "", body, flags=re.S) if page == "wdr-shelf.html" else body
        parts = re.split(r'<h2 id="([^"]+)">(.*?)</h2>', body, flags=re.S)
        docs.append({"id": n, "title": title, "section": "Tools and reference", "href": page, "text": strip(parts[0])}); n += 1
        for i in range(1, len(parts), 3):
            if (page == "wdr-shelf.html" and parts[i] == "shelf") or parts[i].startswith("mp-"):
                continue  # card grid indexed separately below; the map's ranking lists are filled at run time
            docs.append({"id": n, "title": title + ": " + strip(parts[i + 1]), "section": title, "href": page + "#" + parts[i], "text": strip(parts[i + 2])}); n += 1
    # one entry per WDR card
    shelf = open(J("wdr-shelf.html"), encoding="utf-8").read()
    for cid, yr, ttl, txt in re.findall(r'<article class="wdr-card[^"]*" id="(wdr-[0-9]+)"[^>]*>\s*<p class="wdr-year">(.*?)</p>\s*<h3 class="wdr-title"><cite>(.*?)</cite></h3>\s*<p class="wdr-text">(.*?)</p>', shelf, re.S):
        docs.append({"id": n, "title": f"{strip(yr)}: {strip(ttl)}", "section": "WDR shelf", "href": "wdr-shelf.html#" + cid, "text": strip(txt)}); n += 1
    for key, term, d in glossary_terms():
        docs.append({"id": n, "title": term, "section": "Glossary", "href": "glossary.html#" + key, "text": d.replace('\\"', '"')}); n += 1
    with open(J("assets", "js", "search-index.js"), "w", encoding="utf-8") as f:
        f.write("/* Generated by scripts/build_site_meta.py. Do not edit. */\nwindow.WE = window.WE || {};\nWE.SEARCH = "
                + json.dumps(docs, ensure_ascii=False) + ";\n")
    print(f"search-index.js: {len(docs)} documents")


if __name__ == "__main__":
    sources_data()
    search_index()
